#Question 6: Print Numbers from 1 to N
#Problem Statement:
#Write a Python program to accept a number N from the user
# and print all numbers from 1 to N using a while loop.
#Sample Input:
#text
#Enter a number: 5
#Expected Output:
#text
#1
#2
#3
#4
#5
n= int(input("enter a number:"))
i=1
while i<=n:
    print(i)
    i=i+1

